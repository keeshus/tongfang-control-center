def test_style_colors() -> None:
    """
    Test that the generated color codes match the expected values.
    """
    for style, expected_code in EXPECTED_STYLE_CODES.items():
        generated_code = get_light_style_code(style)
        assert (
            generated_code == expected_code
        ), f"Failed for style: {style}. Expected {expected_code}, got {generated_code}"


